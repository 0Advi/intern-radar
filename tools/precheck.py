#!/usr/bin/env python3
"""Free pre-check for the scheduled Claude runs: works out what (if anything) needs Claude, and prints a
compact work list so the run does not have to read tracker.csv, postings.json or details.json itself.

  python3 tools/precheck.py --task link-inbox     # exit 3 = nothing queued: the run should stop at once
  python3 tools/precheck.py --task daily
  python3 tools/precheck.py --task deep-sweep [--sweep-if-stale]
  python3 tools/precheck.py --log "task=daily result=..."   # append the run's own summary to data/usage.jsonl

Every call appends one line to data/usage.jsonl, so Claude runs per day can be counted.
Exit codes: 0 = work for Claude, 3 = nothing to do, 2 = bad arguments.
"""
import csv
import datetime as dt
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
NOTHING = 3


def load(name, default):
    try:
        return json.loads((DATA / name).read_text())
    except (OSError, ValueError):
        return default


def log(entry):
    entry = {"time": dt.datetime.now().isoformat(timespec="minutes"), **entry}
    with open(DATA / "usage.jsonl", "a") as f:
        f.write(json.dumps(entry, ensure_ascii=False) + "\n")


def last_sweep_age_h():
    sweeps = load("sweep_log.json", [])
    if not sweeps:
        return 999.0
    t = dt.datetime.fromisoformat(sweeps[-1]["time"])
    return (dt.datetime.now() - t).total_seconds() / 3600


def gather():
    today = dt.date.today().isoformat()
    with open(ROOT / "tracker.csv", newline="") as f:
        tracker = list(csv.DictReader(f))
    inbox = load("inbox.json", [])
    details = load("details.json", {})
    postings = load("postings.json", {})
    applied = {u for u, v in load("applied.json", {}).items() if v}

    queued = [i for i in inbox if i.get("status") == "queued"]
    drafts = [r for r in tracker if r["status"] == "drafted"]
    due = []
    for r in tracker:
        if r["status"] == "sent" and r["followup1_date"] and r["followup1_date"] <= today:
            due.append((r, 1))
        elif r["status"] == "followed_up" and r["followup2_date"] and r["followup2_date"] <= today:
            due.append((r, 2))
    unreviewed = [p for u, p in postings.items()
                  if not p.get("gone") and p.get("bucket") == "match" and u not in details and u not in applied
                  and (p.get("auto") or {}).get("verdict") != "no"]
    sent_today = sum(1 for r in tracker if r["date_sent"] == today)
    known = sorted({r["company"] for r in tracker} | {p["company"] for p in postings.values()}, key=str.lower)
    return dict(today=today, tracker=tracker, queued=queued, drafts=drafts, due=due,
                unreviewed=unreviewed, sent_today=sent_today, known=known)


def show(g, task):
    out = [f"# Work list for {task} — {g['today']} (generated by tools/precheck.py; no need to re-read the source files)"]
    if g["queued"]:
        out.append(f"\n## Queued in data/inbox.json ({len(g['queued'])})")
        for i in g["queued"]:
            kind = "cold-email request" if i.get("type") == "mail" else "pasted link"
            out.append(f"- id={i.get('id')} [{kind}] {i.get('text', '')[:200]}" +
                       (f" key={i.get('key')} email={i.get('email')}" if i.get("type") == "mail" else ""))
    if task in ("daily", "deep-sweep"):
        if g["unreviewed"]:
            out.append(f"\n## Board postings with no details.json entry yet ({len(g['unreviewed'])}) — set a verdict for each")
            for p in g["unreviewed"][:25]:
                a = p.get("auto") or {}
                bits = [p.get("location", "")[:60], f"posted {p.get('posted', '')}"]
                if a.get("reasons"):
                    bits.append("pre-screen: " + "; ".join(a["reasons"]))
                if a.get("stipend"):
                    bits.append("pay: " + a["stipend"][:80])
                out.append(f"- {p['company']} | {p['title']} | " + " | ".join(b for b in bits if b) + f"\n  {p['url']}")
            out.append("  Full posting text: `python3 tools/fetch_details.py --show` (prints every posting; grep for the URL).")
    if task in ("daily", "deep-sweep") and (DATA / "cards.json").exists():
        r = subprocess.run([sys.executable, str(ROOT / "tools/triage.py"), "--show", "12"],
                           capture_output=True, text=True)
        if r.stdout.strip():
            out.append("\n## Tier-1 cards (cheap model, quotes verified; TRIAL: advisory only — still judge each role "
                       "yourself and record the verdict in details.json)\n" + r.stdout.strip())
    if task == "daily":
        out.append(f"\n## Outreach state\n- Emails sent today so far: {g['sent_today']} (daily cap in CLAUDE.md)")
        if g["drafts"]:
            out.append(f"- Drafts still waiting for Aditya's approval: " + ", ".join(r["company"] for r in g["drafts"]))
        if g["due"]:
            out.append("- Follow-ups due:")
            for r, n in g["due"]:
                out.append(f"  - follow-up {n}: {r['company']} <{r['contact_email']}> first sent {r['date_sent']} "
                           f"(tracker id {r['id']})")
        else:
            out.append("- No follow-ups due.")
    if task in ("daily", "deep-sweep"):
        out.append(f"\n## Companies already known (skip these when searching) — {len(g['known'])}\n" +
                   ", ".join(g["known"]))
    print("\n".join(out))


def main():
    args = sys.argv[1:]
    if args[:1] == ["--log"]:
        log({"note": " ".join(args[1:])[:300]})
        return 0
    if "--task" not in args:
        print(__doc__)
        return 2
    task = args[args.index("--task") + 1]
    if task not in ("link-inbox", "daily", "deep-sweep"):
        print(f"unknown task {task}")
        return 2
    if "--sweep-if-stale" in args and last_sweep_age_h() > 6:
        subprocess.run(["/bin/zsh", str(ROOT / "tools/run_sweep.sh")], check=False)
    g = gather()
    work = {"queued": len(g["queued"]), "unreviewed": len(g["unreviewed"]), "followups": len(g["due"]),
            "drafts": len(g["drafts"])}
    if task == "link-inbox" and not g["queued"]:
        log({"task": task, "result": "skipped: nothing queued", **work})
        print("NOTHING TO DO — nothing queued. Stop now without reading any other file.")
        return NOTHING
    log({"task": task, "result": "work", **work})
    show(g, task)
    return 0


if __name__ == "__main__":
    sys.exit(main())
